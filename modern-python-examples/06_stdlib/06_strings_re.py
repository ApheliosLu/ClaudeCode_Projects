# ================= f-string 语法全貌 =================

# ---- 1. 任意表达式 + {x=} 自调试 ----
name, age = "阿黎", 23
price = 3.14159
print("1) f-string 基础:")
print("   简单插值:", f"用户 {name}, {age} 岁")
print("   任意表达式:", f"明年 {age + 1} 岁, 姓名长度 {len(name)}")
# 这是什么: {x=} —— 3.8+ 的"自调试"语法: 自动写成 "x=值",
#           打印中间变量不用再手敲名字, 调试输出一行一个变量最省事。
print("   自调试 {age=}:", f"{age=}", " {name=}:", f"{name=}")

# ---- 2. 格式说明符: 对齐 / 补零 / 小数位 / 百分比 ----
print("\n2) 格式说明符(冒号后的部分):")
print("   补零 {num:06d}:", f"{42:06d}", "   # 6 位宽, 前面补 0")
print("   小数 {pi:.2f}:", f"{price:.2f}", "   # 两位小数")
print("   百分比 {frac:.1%}:", f"{0.853:.1%}", "   # 小数直接转百分数")
print("   对齐 {s:>8}:", f"{'右对齐':>8}", f"{'左对齐':<8}", "← 宽度 8")
# 这是什么: {表达式:格式} —— 冒号后是格式说明: 06d=补零整型、.2f=两位小数、
#           .1%=百分数、>8/=左对齐右对齐宽度。和旧写法 "%06d" % x 等价,
#           但写在花括号里直观看得见。

# ---- 3. 3.12 的两处大改进: 多行 f-string 与内嵌同引号 ----
d = {"key": "value"}
print("\n3) PEP 701(3.12):")
# (3.12 及之前: 下面的写法全部 SyntaxError —— f"..." 内不能再用双引号,
#   表达式部分也不能跨行/写注释。老代码只能用 f"{d['key']}" 绕行 + 变量承接。)
print("   内嵌同引号 :", f"{d["key"]}")          # 3.12 前: 必须写成 f"{d['key']}"
# 这是什么: PEP 701(3.12 起) —— 重写了 f-string 语法: 引号可随意嵌套、
#           表达式部分还能跨行书写(甚至带 # 注释), 复杂的拼接不再需要变量:
long_expr = f"总和 = {
    1 + 2 + 3        # 表达式折行 + 注释, 3.12 起合法
}"
print("   表达式折行 :", long_expr)
print(f"   ↑ 本机 3.14 编译运行无 SyntaxError (3.12 及之前: 折行直接报错)")

# ---- 4. str.format 与 % 老写法对照(读老代码用) ----
print("\n4) 老写法对照(会读就行, 新代码写 f-string):")
print("   %-格式化 :", "%s %d 岁, 价格 %.2f" % (name, age, price))
print("   .format  :", "{} {} 岁".format(name, age))

# ================= 正则表达式 =================

# ---- 5. 原始字符串 r"..." 为什么必须写 r ----
# 这是什么: r"..." —— 原始字符串: 反斜杠不转义。正则里 \d 是"数字"的意思,
#           但在普通字符串里 \d 会被 Python 当转义符处理(非法转义)。
#           正则一律用 r"..." 前缀, 想表达的就是"把 \d 原样交给正则引擎"。
print("\n5) 原始字符串 r 前缀:")
print("   普通字符串 '\\n' 的 repr:", repr("\n"), "  # \\n 被转义成换行符(1 字符)")
print("   原始字符串 r'\\n' 的 repr:", repr(r"\n"), "  # 保持反斜杠+n 两字符")
print("   → 正则模式里有大量 \\d \\s 这类反斜杠, 若写成普通字符串会被 Python")
print("     抢先转义(变成别的意思甚至报错); 加 r 前缀 = 原样交给正则引擎")

# ---- 6. re.compile 预编译 + 命名分组找电话 ----
import re
# 这是什么: re.compile(模式) —— 先编译成"模式对象"再反复用:
#           多次 re.search(模式, s) 每次都要重编译, 循环里用 compile 快得多;
#           编译一次也能同时拿到 group 名等元信息, 是推荐的写法。
# 这是什么: (?P<名字>...) —— 命名分组: 给括号分组起名, 取结果用 m.group("名字"),
#           比数第几个括号(第 1 组第 2 组)可读得多。
phone_pat = re.compile(r"(?P<区号>0\d{2,3})-(?P<号码>\d{7,8})")
text = "客服 010-12345678, 渠道商 021-87654321, 传真 0551-1234567"
print("\n6) 命名分组提取电话号码:")
for m in phone_pat.finditer(text):
    print(f"   找到 {m.group()} → 区号 {m.group('区号')}, 号码 {m.group('号码')}")
# 这是什么: 模式.finditer(文本) —— 迭代所有匹配(match 对象);
#           模式.findall(文本) —— 直接拿所有匹配的字符串列表(下一节用)。

# ---- 7. re.findall + re.sub: 挑出来与替换 ----
# 这是什么: re.sub(模式, 替换, 文本) —— 替换所有匹配; 替换串里 \1 \2 引用
#           第 1/2 组捕获的原文(脱敏/打码/统一格式的标配)。
masked = re.sub(r"(?P<区号>0\d{2,3})-(?P<号码>\d{7,8})", r"\g<区号>-****", text)
print("\n7) 提取与替换:")
print("   findall 电话:", re.findall(r"0\d{2,3}-\d{7,8}", text))
emails = "联系 a.b@example.com 或 hr@my-corp.cn, 非邮箱勿扰"
print("   findall 邮箱:", re.findall(r"[\w.]+@[\w-]+\.\w+", emails))
print("   sub 打码电话 :", masked, "  # \\g<区号> 引用命名分组")

# ---- 8. 分组提取单条: search + group ----
# 这是什么: 模式.search(文本) —— 找第一处匹配, 返回 match 或 None;
#           想取某一段用 .group(组号/组名), 没匹配要判 None(直接 .group 会崩)。
order_line = "订单 #A-7788 金额 ¥299"
m = re.search(r"#(A-\d+)", order_line)
print("\n8) search 提取单条字段:")
print("   匹配串:", m.group(1) if m else "无", "  # 整个订单号在组 1")
print("   金额:", re.search(r"¥(\d+)", order_line).group(1))
